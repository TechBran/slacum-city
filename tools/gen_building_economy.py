#!/usr/bin/env python3
"""Generate `data/building_economy.json` for SLACUM CITY.

Source of truth: `docs/design/03-economy.md` (Round 3; report 98 rulings C-07,
C-16, RR-5, RR-13, RR-16, RR-18).  Nothing is read from disk: doc 03's money
table (s2.2 / s2.13a) and its published `base_tax_by_level` rows are
transcribed verbatim below, every generated column is grown from them by the
s2.3 curve family, and every cell the doc publishes is diffed before a byte is
written.

What this file owns (doc 03 s3.2's contract keys):

    class, build_cost_l1, base_tax_l1, base_tax_by_level,
    upgrade_cost_by_step, capital_value_by_level

Doc 03 s3.2 nominates `data/buildings.json` as the carrier for these keys.  The
shipped `data/buildings.json` is generated by `tools/gen_buildings.py` from doc
02, whose `forbidden_keys` list bans every cost column (report 98 C-07 / C-08),
so the two generators would fight over one file.  The economy columns therefore
ship in their own generated file, keyed by doc 03's archetype ids, with
`doc02_archetype_alias` mapping doc 02's roster onto it.  See MISMATCH below.

Generation contract (doc 03 s2.2 / s2.3):

    base_tax(type, L)        = round( base_tax_l1 x TAX_LEVEL_GROWTH^(L-1) )
    upgrade_cost(type, L->L+1) = round( build_cost_l1 x UPG_COEFF x UPG_GROWTH^(L-1) )
    capital_value(type, L)   = round( build_cost_l1 x V(L) )
    V(L)                     = 1 + (UPG_COEFF/(UPG_GROWTH-1)) x (UPG_GROWTH^(L-1) - 1)

  * `round()` is half-up throughout doc 03 (s2.8's own note), and the
    arithmetic here is `decimal.Decimal` with ROUND_HALF_UP so a tie is a real
    tie and never a binary-float artefact;
  * `V(L)` ships as the 3-dp vector `upgrades.CAPITAL_VALUE_V` in doc 03 s8
    (`[1.000, 2.450, 6.147, 15.576, 39.620]`).  The PUBLISHED capital values are
    generated from that vector, not from the exact closed form -- see
    CAPITAL_VALUE_NOTE, and `published_cell_overrides` in the emitted file;
  * the PUBLISHED `base_tax_by_level` rows are NORMATIVE (report 98 RR-5).
    Where the curve and the published cell disagree the published cell ships and
    the difference is recorded; three cells are affected, all by exactly $1.

Usage:
    python3 tools/gen_building_economy.py [--out-dir DATA_DIR] [--check]

    --check   validate only; do not write.
"""

